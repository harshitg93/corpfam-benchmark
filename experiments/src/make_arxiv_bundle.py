"""Assemble the flat arXiv submission bundle from the canonical manuscript sources.

arXiv compiles from the root of the uploaded directory, so paper/latex/main.tex cannot
be uploaded as it stands: it reaches into ../shared/ and ../refs/, and those paths escape
the submission root and cannot resolve. This script writes paper/arxiv-submission/, which
holds the same manuscript with every include rewritten to a sibling file and no
parent-relative path anywhere.

The bibliography is inlined as main.bbl with \\input rather than \\bibliography, so the
document carries its own reference list and neither arXiv nor a local build needs to
locate refs.bib. That also makes the bundle verifiable: tectonic reruns BibTeX when it
sees a \\bibliography command, and with no .bib alongside it silently overwrites a
shipped .bbl with an empty one, handing back a PDF with no references and a verification
that passed for the wrong reason.

Regenerate after any change to the manuscript body, the tables, or the bibliography:

    python3 experiments/src/make_arxiv_bundle.py
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

PAPER = Path("paper")
SRC_MAIN = PAPER / "latex" / "main.tex"
TABLES = PAPER / "latex" / "tables"
SHARED = PAPER / "shared"
BIB = PAPER / "refs" / "refs.bib"
OUT = PAPER / "arxiv-submission"
TECTONIC = shutil.which("tectonic") or str(Path.home() / "bin" / "tectonic")

# Exactly what gets uploaded. Anything else in the directory is either a build artifact
# arXiv tells you to leave out, or a file the document does not use -- both are covered
# by arXiv's own "extraneous files" exclusion.
MANIFEST = (["main.tex", "main.bbl", "abstract.tex", "body.tex"]
            + sorted(p.name for p in TABLES.glob("*.tex")))

# main.tex reaches outside its directory in these places. Each maps to a sibling file.
REWRITES = [
    (r"\newcommand{\tabledir}{tables}", r"\newcommand{\tabledir}{.}"),
    (r"\input{tables/macros}", r"\input{macros}"),
    (r"\input{../shared/abstract}", r"\input{abstract}"),
    (r"\input{../shared/body}", r"\input{body}"),
    # The .bbl is shipped, so the style is only a record of how it was produced.
    (r"\bibliographystyle{plainnat}",
     r"% Bibliography pre-compiled with plainnat; main.bbl is inlined below."),
    (r"\bibliography{../refs/refs}", r"\input{main.bbl}"),
    # The source header describes where the shared body lives in the repo. Inside the
    # bundle that is no longer true, and a reader of the uploaded main.tex should not be
    # pointed at a directory the upload does not contain.
    ("% arXiv / preprint build. The manuscript body lives in ../shared/body.tex and is\n"
     "% shared verbatim with the PVLDB build in ../pvldb, so the two cannot drift.\n",
     ""),
]

HEADER = """\
% arXiv submission build -- GENERATED by experiments/src/make_arxiv_bundle.py.
% Do not edit. Edit paper/shared/, paper/latex/ or paper/refs/ and regenerate.
%
% Flat by construction: every file this document needs is a sibling, so the directory
% compiles unchanged from whatever root arXiv unpacks it into.
"""


def run(cmd: list[str], cwd: Path) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True)


def build_bbl(stage: Path) -> Path:
    """Compile the manuscript once with refs.bib present, to produce main.bbl."""
    for t in TABLES.glob("*.tex"):
        shutil.copy2(t, stage / t.name)
    shutil.copy2(SHARED / "abstract.tex", stage / "abstract.tex")
    shutil.copy2(SHARED / "body.tex", stage / "body.tex")
    shutil.copy2(BIB, stage / "refs.bib")

    text = SRC_MAIN.read_text(encoding="utf-8")
    for old, new in REWRITES[:4]:
        text = text.replace(old, new)
    text = text.replace(r"\bibliography{../refs/refs}", r"\bibliography{refs}")
    (stage / "main.tex").write_text(text, encoding="utf-8")

    r = run([TECTONIC, "--keep-intermediates", "main.tex"], stage)
    bbl = stage / "main.bbl"
    if r.returncode != 0 or not bbl.exists():
        sys.exit(f"could not build main.bbl:\n{r.stderr[-2000:]}")
    if not re.search(r"\\bibitem", bbl.read_text(encoding="utf-8")):
        sys.exit("main.bbl was produced but contains no \\bibitem entries")
    return bbl


def verify(bundle: Path) -> tuple[int, list[str]]:
    """Compile a copy of the bundle in isolation, exactly as arXiv would.

    Copying to a scratch directory rather than building in place proves the bundle is
    self-contained wherever it is unpacked, and leaves the committed directory holding
    submission files only.
    """
    shipped_bbl = (bundle / "main.bbl").read_bytes()
    with tempfile.TemporaryDirectory() as td:
        scratch = Path(td) / "arxiv-submission"
        shutil.copytree(bundle, scratch)
        r = run([TECTONIC, "--keep-logs", "main.tex"], scratch)
        if r.returncode != 0:
            sys.exit(f"bundle failed to compile:\n{r.stderr[-3000:]}")
        if not (scratch / "main.pdf").exists():
            sys.exit("bundle compiled but produced no PDF")
        if (scratch / "main.bbl").read_bytes() != shipped_bbl:
            sys.exit("the build overwrote main.bbl; the shipped bibliography is unsafe")
        log = (scratch / "main.log").read_text(encoding="utf-8", errors="replace")
        pages = re.findall(r"Output written on main\.(?:pdf|xdv) \((\d+) pages", log)
        bad = [ln.strip() for ln in log.splitlines()
               if re.search(r"undefined (reference|citation)", ln, re.I)
               or "Undefined control sequence" in ln]
        return (int(pages[0]) if pages else 0), bad


def main() -> int:
    if not Path(TECTONIC).exists():
        sys.exit(f"tectonic not found at {TECTONIC}")

    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    with tempfile.TemporaryDirectory() as td:
        shutil.copy2(build_bbl(Path(td)), OUT / "main.bbl")

    for t in sorted(TABLES.glob("*.tex")):
        shutil.copy2(t, OUT / t.name)
    shutil.copy2(SHARED / "abstract.tex", OUT / "abstract.tex")
    shutil.copy2(SHARED / "body.tex", OUT / "body.tex")

    text = SRC_MAIN.read_text(encoding="utf-8")
    for old, new in REWRITES:
        if old not in text:
            sys.exit(f"expected to rewrite {old!r} in {SRC_MAIN}, but it is absent")
        text = text.replace(old, new)
    (OUT / "main.tex").write_text(HEADER + text, encoding="utf-8")

    # A single surviving ../ would compile here and fail on arXiv, which is the exact
    # failure this script exists to prevent, so treat it as fatal rather than a warning.
    for f in sorted(OUT.glob("*.tex")):
        for n, line in enumerate(f.read_text(encoding="utf-8").splitlines(), 1):
            if "../" in re.sub(r"(?<!\\)%.*", "", line):
                sys.exit(f"parent-relative path survives at {f.name}:{n}: {line.strip()}")

    # arXiv's figure rules are a separate class of failure and this paper has no
    # figures: every exhibit is an \input-ed LaTeX table. Assert it, so that adding a
    # figure later breaks the build rather than the submission.
    figures = [f.name for f in sorted(OUT.glob("*.tex"))
               if r"\includegraphics" in f.read_text(encoding="utf-8")]
    if figures:
        sys.exit(f"figures appeared in {figures}; arXiv's figure rules now apply and "
                 "this script does not handle them")

    # arXiv auto-detects the top-level file. More than one candidate invites it to pick
    # the wrong one.
    entry = [f.name for f in sorted(OUT.glob("*.tex"))
             if r"\documentclass" in f.read_text(encoding="utf-8")]
    if entry != ["main.tex"]:
        sys.exit(f"exactly one file may carry \\documentclass, found {entry}")

    found = sorted(p.name for p in OUT.iterdir())
    if found != sorted(MANIFEST):
        extra, missing = set(found) - set(MANIFEST), set(MANIFEST) - set(found)
        sys.exit(f"bundle contents differ from the manifest; "
                 f"unexpected={sorted(extra)} missing={sorted(missing)}")

    pages, bad = verify(OUT)
    size = sum(p.stat().st_size for p in OUT.iterdir())
    print(f"wrote {OUT}/ ({len(found)} files, {size / 1024:.0f} KiB)")
    for f in found:
        print(f"  {f:<22s} {(OUT / f).stat().st_size:>7,d} B")
    print(f"\ncompiled standalone in a scratch copy: {pages} pages")
    print("no parent-relative paths, no figures, one \\documentclass")
    if bad:
        print("\nFAILED - unresolved references:")
        for b in bad:
            print(f"  - {b}")
        return 1
    print("no undefined references or citations")
    print("main.bbl byte-identical after the build: the shipped bibliography is the "
          "one typeset")
    return 0


if __name__ == "__main__":
    sys.exit(main())
