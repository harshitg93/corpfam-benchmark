"""Generate LaTeX macros and tables for the CorpFam paper from results JSON.

Every number that appears in the manuscript is defined here as a macro and read from
a results file. Nothing is typed by hand into the prose. This is not fastidiousness
for its own sake: it means a rerun of the experiments propagates to the paper, and a
claim in the text can always be traced to the file and key that produced it. The
companion verifier reads the same macros and refuses any bare numeral in the body.

Usage:
    python3 experiments/src/make_tables.py
"""

from __future__ import annotations

import json
from pathlib import Path

RES = Path("experiments/results")
OUT = Path("paper/latex")
TAB = OUT / "tables"

METHOD_LABEL = {
    "exact": "Exact (normalised)",
    "jaccard": "Token Jaccard",
    "seqratio": "Sequence ratio",
    "tfidf_char": "TF--IDF char 3-gram",
    "embedding": "MiniLM embedding",
}
STRING_METHODS = ["exact", "jaccard", "seqratio", "tfidf_char"]
ALL_METHODS = STRING_METHODS + ["embedding"]
VIS_ORDER = ["identical", "visible", "invisible"]
VIS_LABEL = {"identical": "Identical", "visible": "Visible", "invisible": "Invisible"}
NEG_LABEL = {"random": "Random", "hard_string": "Hard string", "same_block": "Same block"}


def load(name: str) -> dict:
    return json.loads((RES / f"{name}.json").read_text(encoding="utf-8"))


def fmt(n: float | int, dp: int = 0) -> str:
    if isinstance(n, int) or dp == 0:
        return f"{int(round(float(n))):,}"
    return f"{float(n):,.{dp}f}"


def main() -> None:
    build = load("benchmark_build")
    base = load("string_baselines")
    base.update(load("embedding_baseline"))  # same protocol, same metric shape
    recon = load("parent_source_reconciliation")
    arch = load("archive_parents")
    audit = load("ground_truth_audit")

    TAB.mkdir(parents=True, exist_ok=True)
    m: list[str] = ["% Generated by experiments/src/make_tables.py. Do not edit.",
                    "% Every numeric claim in the manuscript resolves to a macro here.", ""]

    def mac(name: str, val: str) -> None:
        m.append(f"\\newcommand{{\\{name}}}{{{val}\\xspace}}")

    # --- Corpus and ground truth -------------------------------------------------
    mac("ArchiveRows", fmt(arch["rows_read"]))
    mac("ArchiveEntities", fmt(arch["distinct_uei"]))
    mac("ArchiveSelfParent", fmt(arch["self_parent"]))
    mac("ArchiveGenuineLinks", fmt(arch["genuine_parent_links"]))
    mac("ArchiveConflicting", fmt(arch["entities_with_conflicting_parents"]))
    selfpct = 100.0 * arch["self_parent"] / (arch["distinct_uei"] - arch["blank_parent"])
    mac("ArchiveSelfParentPct", f"{selfpct:.1f}\\%")

    mac("AuditRecords", fmt(audit["records_total"]))
    mac("AuditChildRecords", fmt(audit["child_level_records"]))
    mac("AuditSelfParentPct", f'{audit["self_parent"]["pct_of_child_records"]:.1f}\\%')
    mac("AuditGenuineLinks", fmt(audit["genuine_parent_child_links"]))
    mac("AuditMultiParent", fmt(audit["parents_array"]["records_with_more_than_one_parent"]))
    mac("AuditMaxParents", fmt(audit["parents_array"]["max_parents_on_any_record"]))
    mac("AuditTopOnePctShare", f'{audit["spend_on_genuine_links"]["top_1pct_share"]:.1f}\\%')
    mac("AuditTopTenPctShare", f'{audit["spend_on_genuine_links"]["top_10pct_share"]:.1f}\\%')

    # --- Source reconciliation ---------------------------------------------------
    c = recon["comparison"]
    mac("ReconBoth", fmt(c["both_report_a_distinct_parent"]))
    mac("ReconAgreeUei", f'{c["pct_agree_uei"]:.1f}\\%')
    mac("ReconAgreeName", f'{c["pct_agree_name"]:.1f}\\%')
    mac("ReconAgreeToken", f'{c["pct_agree_token"]:.1f}\\%')
    lo, hi = c["wilson95_pct_agree_name"]
    mac("ReconAgreeNameCI", f"[{lo:.1f}, {hi:.1f}]")
    mac("ReconDisagree", fmt(c["substantively_different_parent"]))
    disag_pct = 100.0 * c["substantively_different_parent"] / c["both_report_a_distinct_parent"]
    mac("ReconDisagreePct", f"{disag_pct:.1f}\\%")
    mac("ReconOnlyOne", fmt(c["only_one_source_reports_a_parent"]))

    nv = recon["name_visibility_archive"]
    mac("NvIdenticalRaw", fmt(nv["name_identical_trivial"]))
    mac("NvInformative", fmt(nv["informative_links"]))
    mac("NvInvisiblePctInformative", f'{nv["pct_of_informative"]:.1f}\\%')

    # --- Benchmark composition ---------------------------------------------------
    mac("BenchFamilies", fmt(build["families"]))
    mac("BenchPairs", fmt(build["pairs_total"]))
    mac("BenchPositives", fmt(build["positives"]))
    mac("BenchNegatives", fmt(build["negatives"]))
    mac("BenchDroppedArtifact", fmt(build["dropped"]["manually_adjudicated_artifact"]))
    mac("BenchDroppedSovereign", fmt(build["dropped"]["sovereign_entity"]))
    log = build.get("inspection_log", {})
    n_excl = sum(1 for d in log.values() if d["verdict"] == "exclude")
    n_ret = sum(1 for d in log.values() if d["verdict"] == "retain")
    mac("BenchExcludedParents", fmt(n_excl))
    mac("BenchInspected", fmt(len(log)))
    mac("BenchRetained", fmt(n_ret))
    mac("BenchSovereignAll", fmt(len(build.get("sovereign_parents_excluded_all", []))))
    dbs = build.get("dropped_by_stratum", {})
    man_tot = sum(v for k, v in dbs.items() if k.startswith("manual_"))
    if man_tot:
        mac("BenchDropInvisiblePct",
            f'{100.0 * dbs.get("manual_invisible", 0) / man_tot:.1f}\\%')
    mac("BenchSeed", str(build["seed"]))
    for k, v in build["visibility_of_positives"].items():
        mac(f"BenchPos{k.capitalize()}", fmt(v))
        pct = 100.0 * v / build["positives"]
        mac(f"BenchPos{k.capitalize()}Pct", f"{pct:.1f}\\%")
    for sp, v in build["positive_split_sizes"].items():
        mac(f"BenchPos{sp.capitalize()}", fmt(v))
    for sp, v in build["split_sizes"].items():
        mac(f"BenchPairs{sp.capitalize()}", fmt(v))

    # --- Per-stratum majority baselines ------------------------------------------
    # Positive rates differ by an order of magnitude across strata, so an F1 in one
    # stratum cannot be compared with an F1 in another. These are the scores of a
    # classifier that simply answers "yes" to everything, and every reported cell is
    # read against them.
    br = build["test_base_rates"]
    for v in VIS_ORDER:
        if v in br:
            # Recomputed from the raw counts. Formatting the manifest's already-rounded
            # field would round twice and drift by a tenth against the verifier.
            rate = br[v]["test_positives"] / br[v]["test_pairs"]
            mac(f"Base{v.capitalize()}Rate", f"{100 * rate:.1f}\\%")
            mac(f"Base{v.capitalize()}F", f"{100 * (2 * rate / (rate + 1)):.1f}")

    # --- Headline baseline numbers ----------------------------------------------
    # Ranked by average precision, which is threshold-free, rather than by an F1 whose
    # value depends on where the threshold happened to land.
    best = max(base, key=lambda k: base[k]["test"].get("average_precision")
               or base[k]["test"]["overall"]["f1"])
    for v in VIS_ORDER:
        d = base[best]["test"]["by_visibility"].get(v)
        if d:
            mac(f"BestRecall{v.capitalize()}", f'{d["recall"]:.1f}\\%')
            mac(f"BestRecall{v.capitalize()}CI",
                f'[{d["recall_wilson95"][0]:.1f}, {d["recall_wilson95"][1]:.1f}]')
    worst_inv_r = min(v["test"]["by_visibility"]["invisible"]["recall"]
                      for v in base.values())
    best_inv_r = max(v["test"]["by_visibility"]["invisible"]["recall"]
                     for v in base.values())
    mac("AnyInvisibleRecallMax", f"{best_inv_r:.1f}\\%")
    mac("AnyInvisibleRecallMin", f"{worst_inv_r:.1f}\\%")
    if base[best]["test"].get("average_precision") is not None:
        mac("BestAP", f'{base[best]["test"]["average_precision"]:.1f}')
    mac("BestMethod", METHOD_LABEL[best])
    mac("BestOverallF", f'{base[best]["test"]["overall"]["f1"]:.1f}')
    mac("BestIdenticalF", f'{base[best]["test"]["by_visibility"]["identical"]["f1"]:.1f}')
    mac("BestVisibleF", f'{base[best]["test"]["by_visibility"]["visible"]["f1"]:.1f}')
    mac("BestInvisibleF", f'{base[best]["test"]["by_visibility"]["invisible"]["f1"]:.1f}')
    swr = base[best]["test"]["spend_weighted_recall"]
    mac("BestSpendRecall", f"{swr:.1f}\\%" if swr is not None else "n/a")
    mac("BestOverallRecall", f'{base[best]["test"]["overall"]["recall"]:.1f}')
    mac("BestOverallPrec", f'{base[best]["test"]["overall"]["precision"]:.1f}')

    worst_inv = min(v["test"]["by_visibility"]["invisible"]["f1"] for v in base.values())
    best_inv = max(v["test"]["by_visibility"]["invisible"]["f1"] for v in base.values())
    best_inv_method = max(base, key=lambda k: base[k]["test"]["by_visibility"]["invisible"]["f1"])
    mac("AnyInvisibleFMax", f"{best_inv:.1f}")
    mac("AnyInvisibleFMin", f"{worst_inv:.1f}")
    mac("BestInvisibleMethod", METHOD_LABEL[best_inv_method])
    gap = base[best]["test"]["by_visibility"]["identical"]["f1"] - best_inv
    mac("VisibilityGap", f"{gap:.1f}")
    mac("NumMethods", str(len(ALL_METHODS)))
    mac("NumStringMethods", str(len(STRING_METHODS)))

    # The embedding baseline exists to answer the obvious objection to the string
    # results, so its numbers get their own macros rather than being read off a table.
    emb = base["embedding"]
    mac("EmbModel", "MiniLM-L6-v2")
    mac("EmbNames", fmt(emb["unique_names_encoded"]))
    mac("EmbDim", str(emb["embedding_dim"]))
    mac("EmbOverallF", f'{emb["test"]["overall"]["f1"]:.1f}')
    mac("EmbIdenticalF", f'{emb["test"]["by_visibility"]["identical"]["f1"]:.1f}')
    mac("EmbVisibleF", f'{emb["test"]["by_visibility"]["visible"]["f1"]:.1f}')
    mac("EmbInvisibleF", f'{emb["test"]["by_visibility"]["invisible"]["f1"]:.1f}')
    best_string_inv = max(base[k]["test"]["by_visibility"]["invisible"]["f1"]
                          for k in STRING_METHODS)
    mac("BestStringInvisibleF", f"{best_string_inv:.1f}")
    mac("EmbOverStringInvisible",
        f'{emb["test"]["by_visibility"]["invisible"]["f1"] - best_string_inv:.1f}')

    fpk = base[best]["test"]["false_positive_rate_by_negative_kind"]
    for k, v in fpk.items():
        if v["rate_pct"] is not None:
            mac(f"BestFpr{''.join(w.capitalize() for w in k.split('_'))}",
                f'{v["rate_pct"]:.1f}\\%')

    # --- Blocking ----------------------------------------------------------------
    blk_path = RES / "blocking_analysis.json"
    if blk_path.exists():
        b = json.loads(blk_path.read_text(encoding="utf-8"))
        sch = b["schemes"]
        mac("BlkEntities", fmt(b["roster_entities"]))
        mac("BlkPairSpace", fmt(b["naive_pair_space"]))
        tokb = sch["Token blocking"]
        mac("BlkTokenPC", f'{tokb["pair_completeness_pct"]:.1f}\\%')
        mac("BlkTokenRR", f'{tokb["reduction_ratio_pct"]:.2f}\\%')
        mac("BlkTokenInvisible",
            f'{tokb["by_visibility"]["invisible"]["pair_completeness_pct"]:.2f}\\%')
        uni = sch["Union: all schemes"]
        mac("BlkUnionPC", f'{uni["pair_completeness_pct"]:.1f}\\%')
        mac("BlkUnionInvisible",
            f'{uni["by_visibility"]["invisible"]["pair_completeness_pct"]:.1f}\\%')
        mac("BlkInvisibleLost",
            f'{100.0 - uni["by_visibility"]["invisible"]["pair_completeness_pct"]:.1f}\\%')
        # The schemes that are not functions of core(), which carry the empirical
        # content once the definitional rows are set aside.
        for key, short in (("Embedding ANN (MiniLM, k=20)", "Ann"),
                           ("Q-gram blocking (q=4)", "Qgram"),
                           ("Phonetic (Soundex)", "Phon"),
                           ("Attribute (ZIP / city-state)", "Attr"),
                           ("Sorted neighbourhood (w=20)", "Sn")):
            if key in sch:
                mac(f"Blk{short}Invisible",
                    f'{sch[key]["by_visibility"]["invisible"]["pair_completeness_pct"]:.2f}\\%')
                mac(f"Blk{short}PC", f'{sch[key]["pair_completeness_pct"]:.1f}\\%')
        mac("BlkNumSchemes", str(sum(1 for k in sch if not k.startswith("Union"))))
        mac("BlkAnnK", str(b.get("ann_k", 20)))

        rows = []
        order = ["Token blocking", "First-token blocking", "Q-gram blocking (q=4)",
                 "Sorted neighbourhood (w=20)", "Phonetic (Soundex)",
                 "Attribute (ZIP / city-state)", "Embedding ANN (MiniLM, k=20)",
                 "Union: string-keyed", "Union: all schemes"]
        for k in order:
            if k not in sch:
                continue
            s = sch[k]
            v = s["by_visibility"]
            if k == "Union: string-keyed":
                rows.append("\\midrule")
            dagger = "$^\\dagger$" if s.get("keyed_on_core_tokens") else ""
            rows.append(
                f"{k}{dagger} & {s['candidates']:,} & "
                f"{s['pair_completeness_pct']:.1f} & "
                f"{s['reduction_ratio_pct']:.3f} & "
                + " & ".join(f"{v.get(x, {}).get('pair_completeness_pct', 0):.2f}"
                             for x in VIS_ORDER) + " \\\\")
        (TAB / "blocking.tex").write_text("""\
\\begin{table*}[t]
\\centering
\\small
\\begin{tabular}{lrrrrrr}
\\toprule
& & & & \\multicolumn{3}{c}{Pair completeness by visibility} \\\\
\\cmidrule(lr){5-7}
Blocking scheme & Candidates & PC (\\%) & RR (\\%) & Identical & Visible & Invisible \\\\
\\midrule
""" + "\n".join(rows) + """
\\bottomrule
\\end{tabular}
\\caption{Blocking over the full recipient roster, not merely the entities appearing in
our pairs file. PC is pair completeness, the recall of true links into the candidate
set; RR is reduction ratio. Rows marked $^\\dagger$ key on the same \\texttt{core()}
token function that \\emph{defines} the invisible stratum, so their zero recall there is
an identity and not a measurement. The informative rows are the others: character
q-grams, sorted-neighbourhood adjacency, phonetic keys, attribute keys that ignore the
name entirely, and semantic nearest neighbours in an embedding space. None of them
exceeds three percent on the invisible stratum, and unioning every scheme still leaves
the overwhelming majority of those links outside the candidate set. The failure is
therefore a property of candidate generation rather than of any particular key.}
\\label{tab:blocking}
\\end{table*}
""", encoding="utf-8")

    # --- EDGAR corroboration ------------------------------------------------------
    ed_path = RES / "edgar_reconciliation.json"
    if ed_path.exists():
        e = json.loads(ed_path.read_text(encoding="utf-8"))
        mac("EdgarFilings", fmt(e["exhibit21_filings_used"]))
        mac("EdgarLinks", fmt(e["links_checked"]))
        mac("EdgarConfirmPct", f'{e["confirmation_rate_pct"]:.1f}\\%')
        inv = e["by_visibility"]["invisible"]
        mac("EdgarInvisibleConfirmPct", f'{inv["confirmation_rate_pct"]:.1f}\\%')
        mac("EdgarInvisibleChecked", fmt(inv["checked"]))
        mac("EdgarInvisibleCI",
            f'[{inv["wilson95"][0]:.1f}, {inv["wilson95"][1]:.1f}]')
        pc2 = e.get("permutation_control", {})
        if pc2:
            mac("EdgarRandomParentPct", f'{pc2["invisible_random_parent_pct"]:.2f}\\%')
            mac("EdgarNearestSizePct",
                f'{pc2["invisible_nearest_size_parent_pct"]:.2f}\\%')
            mac("EdgarExcessOverChance", f'{pc2["excess_over_chance_points"]:.1f}')
            mac("EdgarPermutations", str(pc2["permutations"]))
        rho = e.get("parser_yield_association", {}).get(
            "spearman_rho_filing_length_vs_confirmation")
        if rho is not None:
            mac("EdgarYieldRho", f"{rho:.2f}")
        erows = "\n".join(
            f"{VIS_LABEL[v]} & {d['checked']:,} & {d['confirmed']:,} & "
            f"{d['confirmation_rate_pct']:.1f} & "
            f"[{d['wilson95'][0]:.1f}, {d['wilson95'][1]:.1f}] \\\\"
            for v, d in sorted(e["by_visibility"].items(),
                               key=lambda kv: VIS_ORDER.index(kv[0])))
        (TAB / "edgar.tex").write_text(f"""\
\\begin{{table}}[t]
\\centering
\\small
\\begin{{tabular}}{{lrrrr}}
\\toprule
Stratum & Checked & Confirmed & \\% & 95\\% CI \\\\
\\midrule
{erows}
\\midrule
All & {e['links_checked']:,} & {e['links_confirmed']:,} & {e['confirmation_rate_pct']:.1f} &
[{e['confirmation_wilson95'][0]:.1f}, {e['confirmation_wilson95'][1]:.1f}] \\\\
\\midrule
\\multicolumn{{5}}{{l}}{{\\emph{{Invisible stratum against controls}}}} \\\\
\\quad wrong parent, {pc2.get('permutations', 0)} permutations & -- & -- &
{pc2.get('invisible_random_parent_pct', 0):.2f} & -- \\\\
\\quad nearest-size wrong parent & -- & -- &
{pc2.get('invisible_nearest_size_parent_pct', 0):.2f} & -- \\\\
\\bottomrule
\\end{{tabular}}
\\caption{{Independent corroboration against SEC Exhibit~21 subsidiary schedules over
{e['exhibit21_filings_used']} filings. Exhibit~21 is filed under securities law by the
parent's own counsel and shares no provenance with a supplier's procurement
registration. The control rows re-run the identical matcher against the wrong parent's
filing: chance corroboration is near zero, so the invisible-stratum rate is not an
artifact of long filings or a permissive matcher, and the stratum consists of genuine
corporate relationships rather than registry noise. Non-confirmation is weak evidence
in the other direction, since Exhibit~21 omits immaterial subsidiaries and its
formatting is unregulated.}}
\\label{{tab:edgar}}
\\end{{table}}
""", encoding="utf-8")

    # --- Multi-attribute ----------------------------------------------------------
    ma_path = RES / "multiattribute_baseline.json"
    if ma_path.exists():
        m2 = json.loads(ma_path.read_text(encoding="utf-8"))
        fs = m2["feature_sets"]
        mac("AttrCoveragePct",
            f'{m2["test_pairs_with_address_on_both_sides_pct"]:.1f}\\%')
        mac("AttrEntities", fmt(m2["entities_with_attributes"]))
        mac("AttrSubsetTest", fmt(m2["attributed_subset_sizes"]["test"]))
        # Headline numbers come from the attributed subset; the full split is reported
        # in the table only to show the degeneracy it induces.
        for key, short in (("name_only", "NameOnly"), ("attributes_only", "AttrOnly"),
                           ("combined", "Combined")):
            t = fs[f"{key}__attributed_subset"]["test"]
            mac(f"Ma{short}F", f'{t["overall"]["f1"]:.1f}')
            mac(f"Ma{short}Invisible",
                f'{t["by_visibility"]["invisible"]["f1"]:.1f}')
        sa = m2["true_pairs_sharing_an_address"]
        if "invisible" in sa and sa["invisible"]["pct"] is not None:
            mac("AttrInvisibleSameAddrPct", f'{sa["invisible"]["pct"]:.1f}\\%')
        marows = "\n".join(
            f"{lbl} & {fs[k]['test']['overall']['precision']:.1f} & "
            f"{fs[k]['test']['overall']['recall']:.1f} & "
            f"{fs[k]['test']['overall']['f1']:.1f} & "
            + " & ".join(
                f"{fs[k]['test']['by_visibility'].get(x, {}).get('f1', 0.0):.1f}"
                for x in VIS_ORDER) + " \\\\"
            for k, lbl in (
                ("name_only__attributed_subset", "Name features only"),
                ("attributes_only__attributed_subset", "Attributes only"),
                ("combined__attributed_subset", "Name $+$ attributes")))
        (TAB / "multiattribute.tex").write_text("""\
\\begin{table*}[t]
\\centering
\\small
\\begin{tabular}{lrrrrrr}
\\toprule
& \\multicolumn{3}{c}{Overall} & \\multicolumn{3}{c}{$F_1$ by name visibility} \\\\
\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}
Feature set & P & R & $F_1$ & Identical & Visible & Invisible \\\\
\\midrule
""" + marows + """
\\bottomrule
\\end{tabular}
\\caption{Supervised logistic regression over name and attribute features, evaluated on
the subset of test pairs carrying attributes (address, city, state, ZIP, country,
phone, doing-business-as name) on \\emph{both} sides. Attribute evidence does supply
something names cannot: on the invisible stratum, where name features score zero by
construction, attributes reach the high twenties. That is real signal and it is worth
having, but it leaves the stratum unsolved. The deeper obstacle is coverage: attributes
exist on both sides for only a small fraction of pairs, because a parent is frequently a
holding entity that never transacts and therefore has no address at all.}
\\label{tab:multiattribute}
\\end{table*}
""", encoding="utf-8")

    # --- Clustering ---------------------------------------------------------------
    cl_path = RES / "clustering_task.json"
    if cl_path.exists():
        c2 = json.loads(cl_path.read_text(encoding="utf-8"))
        tr = c2["test_results"]
        rb, orc = tr["realistic_blocked"], tr["oracle_all_pairs"]
        mac("ClusFamilies", fmt(c2["families_multi_child"]))
        mac("ClusTestFamilies", fmt(rb["families"]))
        mac("ClusBlockedBcubed", f'{rb["bcubed_f1"]:.1f}')
        mac("ClusOracleBcubed", f'{orc["bcubed_f1"]:.1f}')
        mac("ClusBlockedExact", f'{rb["exact_recovery_pct"]:.1f}\\%')
        mac("ClusOracleExact", f'{orc["exact_recovery_pct"]:.1f}\\%')
        mac("ClusBlockedPairF", f'{rb["pairwise_f1"]:.1f}')
        mac("ClusOraclePairF", f'{orc["pairwise_f1"]:.1f}')
        crows = "\n".join(
            f"{lbl} & {d['candidate_pairs']:,} & {d['pairwise_f1']:.1f} & "
            f"{d['bcubed_precision']:.1f} & {d['bcubed_recall']:.1f} & "
            f"{d['bcubed_f1']:.1f} & {d['exact_recovery_pct']:.1f} \\\\"
            for lbl, d in (("Blocked", rb), ("Oracle", orc)))
        (TAB / "clustering.tex").write_text(f"""\
\\begin{{table}}[t]
\\centering
\\footnotesize
\\setlength{{\\tabcolsep}}{{4pt}}
\\begin{{tabular}}{{lrrrrrr}}
\\toprule
& & & \\multicolumn{{3}}{{c}}{{B-cubed}} & Exact \\\\
\\cmidrule(lr){{4-6}}
Condition & Cands & Pair $F_1$ & P & R & $F_1$ & fam.\\ (\\%) \\\\
\\midrule
{crows}
\\bottomrule
\\end{{tabular}}
\\caption{{Family-level clustering over the {c2['families_multi_child']} families with
two or more children, scored on test with thresholds chosen on validation.
\\emph{{Blocked}} takes candidates from token blocking as in deployment;
\\emph{{Oracle}} scores every within-split pair. Removing blocking raises pairwise
$F_1$ but \\emph{{lowers}} exact family recovery, because the additional candidates
introduce false links that merge distinct families through transitivity. Only a small
minority of families are recovered exactly under either condition, and exact recovery
is what a spend rollup depends on.}}
\\label{{tab:clustering}}
\\end{{table}}
""", encoding="utf-8")

    # --- Exclusion sensitivity ----------------------------------------------------
    unf_path = RES / "string_baselines_unfiltered.json"
    unf_build = RES / "benchmark_build_unfiltered.json"
    if unf_path.exists():
        u = json.loads(unf_path.read_text(encoding="utf-8"))
        u_inv = max(v["test"]["by_visibility"]["invisible"]["recall"]
                    for v in u.values())
        f_inv = max(v["test"]["by_visibility"]["invisible"]["recall"]
                    for k, v in base.items() if k in STRING_METHODS)
        mac("SensUnfilteredInvisibleRecall", f"{u_inv:.1f}\\%")
